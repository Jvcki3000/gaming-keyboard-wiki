const MARKS = {
  '0-0': 'Esc',
  '3-2': 'W',
  '3-3': 'A',
  '3-4': 'S',
  '3-5': 'D',
};

export default function KeyboardVisual({ layout = '其他' }) {
  const profile = PROFILES[layout] || PROFILES['其他'] || PROFILES.TKL;
  return (
    <div className="keyboard-visual" aria-label={`${layout} 配列示意图`}>
      {profile.rows.map((row, rowIndex) => (
        <div className="kbd-row" key={rowIndex}>
          {row.map((width, colIndex) => {
            const key = `${rowIndex}-${colIndex}`;
            const label = MARKS[key];
            const accent = key === '0-0' || (rowIndex === 3 && colIndex >= 2 && colIndex <= 5) || key === '4-3';
            return (
              <div
                className={`kbd-key${accent ? ' is-accent' : ''}`}
                key={colIndex}
                style={{ flexGrow: width, flexBasis: `${width * 34}px` }}
              >
                {label || ''}
              </div>
            );
          })}
        </div>
      ))}
    </div>
  );
}
